// Builds the bundled word lists so the game runs fully offline.
//   answers: scripts/answers.txt (5 letters) and scripts/answers4.txt (4 letters), curated
//   guesses: macOS /usr/share/dict/words words of that length + simple "-s" forms
import { readFileSync, writeFileSync, existsSync } from 'node:fs';

const DICT = '/usr/share/dict/words';
if (!existsSync(DICT)) throw new Error(`Dictionary not found at ${DICT}`);
const dict = readFileSync(DICT, 'utf8').split('\n');
const header = '// Generated by scripts/build-words.mjs. Do not edit by hand.\n';

function build(length, source, answersFile, answersName, guessesFile, guessesName) {
  const re = new RegExp(`^[a-z]{${length}}$`);
  const shorter = new RegExp(`^[a-z]{${length - 1}}$`);
  const answers = [
    ...new Set(
      readFileSync(new URL(source, import.meta.url), 'utf8')
        .split('\n')
        .filter((l) => !l.startsWith('#'))
        .join(' ')
        .split(/\s+/)
        .filter(Boolean),
    ),
  ].sort();
  const bad = answers.filter((w) => !re.test(w));
  if (bad.length) throw new Error(`Invalid ${length}-letter answers: ${bad.join(', ')}`);

  const guesses = new Set();
  for (const w of dict) {
    if (re.test(w)) guesses.add(w);
    if (shorter.test(w) && !w.endsWith('s')) guesses.add(w + 's');
  }
  for (const a of answers) guesses.delete(a);
  const extra = [...guesses].sort();

  writeFileSync(
    new URL(`../src/engine/words/${answersFile}`, import.meta.url),
    `${header}export const ${answersName}: readonly string[] = ${JSON.stringify(answers)};\n`,
  );
  writeFileSync(
    new URL(`../src/engine/words/${guessesFile}`, import.meta.url),
    `${header}// Extra accepted guesses (answers are accepted too), packed as ${length}-letter chunks.\nexport const ${guessesName} =\n  '${extra.join('')}';\n`,
  );
  console.log(`${length} letters: answers ${answers.length}, extra guesses ${extra.length}`);
}

build(5, './answers.txt', 'answers.ts', 'ANSWERS', 'guesses.ts', 'GUESSES_PACKED');
build(4, './answers4.txt', 'answers4.ts', 'ANSWERS_4', 'guesses4.ts', 'GUESSES4_PACKED');
