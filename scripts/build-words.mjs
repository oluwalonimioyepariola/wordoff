// Builds the bundled word lists so the game runs fully offline.
//   answers: scripts/answers.txt (curated, common words)
//   guesses: macOS /usr/share/dict/words 5-letter words + simple "-s" forms of 4-letter words
import { readFileSync, writeFileSync, existsSync } from 'node:fs';

const DICT = '/usr/share/dict/words';
const isWord = (w) => /^[a-z]{5}$/.test(w);

const answers = [
  ...new Set(
    readFileSync(new URL('./answers.txt', import.meta.url), 'utf8')
      .split('\n')
      .filter((l) => !l.startsWith('#'))
      .join(' ')
      .split(/\s+/)
      .filter(Boolean),
  ),
].sort();

const bad = answers.filter((w) => !isWord(w));
if (bad.length) throw new Error(`Invalid answers: ${bad.join(', ')}`);

if (!existsSync(DICT)) throw new Error(`Dictionary not found at ${DICT}`);
const dict = readFileSync(DICT, 'utf8').split('\n');
const guesses = new Set();
for (const w of dict) {
  if (isWord(w)) guesses.add(w);
  if (/^[a-z]{4}$/.test(w) && !w.endsWith('s')) guesses.add(w + 's');
}
for (const a of answers) guesses.delete(a);
const extra = [...guesses].sort();

const header = '// Generated by scripts/build-words.mjs. Do not edit by hand.\n';
writeFileSync(
  new URL('../src/engine/words/answers.ts', import.meta.url),
  `${header}export const ANSWERS: readonly string[] = ${JSON.stringify(answers)};\n`,
);
writeFileSync(
  new URL('../src/engine/words/guesses.ts', import.meta.url),
  `${header}// Extra accepted guesses (answers are accepted too), packed as 5-letter chunks.\nexport const GUESSES_PACKED =\n  '${extra.join('')}';\n`,
);
console.log(`answers: ${answers.length}, extra guesses: ${extra.length}`);
